num1 = int(input("Digite um número:"))
num2 = int(input("Digite outro número:"))

soma = num1 + num2
sub = num1 - num2
mult = num1 * num2
div = num1 / num2
div_Inteira = num1 // num2
resto_Div = num1 % num2
potenciacao = num1 ** num2


print(f"A soma de {num1} com {num2} dá: {soma}")
print(f"A subtraçao de {num1} com {num2} dá: {sub}")
print(f"A multiplicaçao de {num1} com {num2} dá: {mult}")
print(f"A divisao de {num1} com {num2} dá: {div}")
print(f"A divisao inteira de {num1} com {num2} dá: {div_Inteira}")
print(f"O resto da div de {num1} com {num2} dá: {resto_Div}")
print(f"A potenciacao de {num1} com {num2} dá: {potenciacao}")